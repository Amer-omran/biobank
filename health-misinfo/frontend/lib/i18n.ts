export const DICTS: Record<Locale, Dict> = { en, ar };

export function translate(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let s = DICTS[locale][key] ?? DICTS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Translate a dynamic key (e.g. "review.status." + value), falling back to the raw value. */
export function translateDynamic(locale: Locale, key: string, fallback: string): string {
  return (DICTS[locale] as Record<string, string>)[key] ?? fallback;
}

export function formatNumber(locale: Locale, n: number | null | undefined, digits = 0): string {
  if (n === null || n === undefined || Number.isNaN(n)) return "—";
  return new Intl.NumberFormat(locale === "ar" ? "ar-SA-u-nu-latn" : "en-US", {
    maximumFractionDigits: digits,
    minimumFractionDigits: digits,
  }).format(n);
}

export function formatDate(locale: Locale, iso: string): string {
  return new Intl.DateTimeFormat(locale === "ar" ? "ar-SA-u-ca-gregory-nu-latn" : "en-GB", {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(new Date(iso));
}
